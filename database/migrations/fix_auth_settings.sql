-- إصلاح إعدادات المصادقة في Supabase
-- هذا الملف يحتوي على تعليمات لتحسين إعدادات الأمان في Supabase

-- ملاحظة: هذه الإعدادات يجب تفعيلها من واجهة Supabase مباشرة
-- لا يمكن تنفيذها من خلال استعلامات SQL مباشرة

-- تعليمات لتفعيل حماية كلمات المرور المسربة
/*
1. قم بتسجيل الدخول إلى لوحة تحكم Supabase على https://app.supabase.com
2. اختر المشروع الذي تريد تفعيل الحماية فيه
3. انتقل إلى قسم "Authentication" من القائمة الجانبية
4. اختر تبويب "Providers" أو "Email"
5. ابحث عن قسم "Security" أو "Password Security"
6. قم بتفعيل خيار "Enable HIBP (Pwned Passwords)" أو "Leaked Password Protection"
7. احفظ التغييرات بالنقر على زر "Save" أو "Update"
*/

-- تعليمات لتفعيل المصادقة متعددة العوامل
/*
1. قم بتسجيل الدخول إلى لوحة تحكم Supabase
2. انتقل إلى قسم "Authentication" من القائمة الجانبية
3. اختر تبويب "MFA" أو "Multi-Factor Auth"
4. قم بتفعيل خيارات المصادقة متعددة العوامل المتاحة
5. احفظ التغييرات بالنقر على زر "Save" أو "Update"
*/

-- تعليمات لتفعيل سياسات كلمة المرور القوية
/*
1. قم بتسجيل الدخول إلى لوحة تحكم Supabase
2. انتقل إلى قسم "Authentication" من القائمة الجانبية
3. اختر تبويب "Providers" أو "Email"
4. ابحث عن قسم "Security" أو "Password Strength"
5. قم بتعديل إعدادات قوة كلمة المرور:
   - الحد الأدنى لطول كلمة المرور: 8 أحرف
   - تفعيل خيار تتطلب حرف كبير واحد على الأقل
   - تفعيل خيار تتطلب حرف صغير واحد على الأقل
   - تفعيل خيار تتطلب رقم واحد على الأقل
   - تفعيل خيار تتطلب رمز خاص واحد على الأقل
6. احفظ التغييرات بالنقر على زر "Save" أو "Update"
*/

-- ملاحظة هامة:
-- لا يمكن التحقق من إعدادات المصادقة أو تغييرها مباشرة من خلال استعلامات SQL
-- يجب استخدام واجهة Supabase الرسومية لتفعيل هذه الإعدادات
-- قد تختلف أسماء الأقسام والخيارات حسب إصدار Supabase المستخدم
